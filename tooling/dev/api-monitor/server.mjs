#!/usr/bin/env node
/**
 * Local API monitor — a Bull-Board-style live view of API HTTP traffic.
 *
 * Runs a recording reverse proxy: point a client at this port instead of the API and
 * every call is forwarded upstream, timed, and pushed to a browser dashboard over SSE.
 *
 *   node tooling/dev/api-monitor/server.mjs
 *   PORT=4000 UPSTREAM=http://localhost:3000 node tooling/dev/api-monitor/server.mjs
 *
 * Dashboard   http://localhost:4000/
 * Proxy       http://localhost:4000/api/v1/...   ->   UPSTREAM/api/v1/...
 *
 * Dev-only. Bodies are buffered in memory (capped, ring-buffered) and Authorization /
 * Cookie values are truncated before they ever reach the browser.
 */
import http from 'node:http';
import { URL } from 'node:url';

const PORT = Number(process.env.PORT || 4000);
const UPSTREAM = process.env.UPSTREAM || 'http://localhost:3000';
const MAX_CALLS = Number(process.env.MAX_CALLS || 2000);
const MAX_BODY = Number(process.env.MAX_BODY || 24_000);

const upstream = new URL(UPSTREAM);

/** Ring buffer of recorded calls, newest last. */
const calls = [];
let seq = 0;
/**
 * Run metadata posted by the load script itself (`POST /__monitor/run`).
 *
 * The dashboard used to GUESS the command from traffic shape and got it wrong — it
 * reported `VUS=78 ITERATIONS=1` for a `VUS=100 RAMP=30s` run, because peak overlap
 * undercounts a ramp. Having the script state its own parameters is exact; inference
 * is only the fallback when something other than the scenario is driving traffic.
 */
let runMeta = null;
/** Connected dashboard clients (SSE). */
const clients = new Set();

/* ─────────────────────────── helpers ─────────────────────────── */

/** Collapse volatile path segments so stats group by route, not by instance. */
function normalizePath(pathname) {
  return pathname
    .split('/')
    .map((seg) => {
      if (/^(org|usr|ses|sub|inv|key|ntf|whk|upl|mfa|cred|exp)_[a-z0-9]+$/i.test(seg)) return ':id';
      if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(seg))
        return ':uuid';
      if (/^\d+$/.test(seg)) return ':n';
      // slugs generated by the load scenario / onboarding
      if (/^k6-org-[\w-]+$/i.test(seg)) return ':slug';
      return seg;
    })
    .join('/');
}

/** Never ship a full credential to the browser — enough to correlate, not to reuse. */
function redactHeaders(headers) {
  const out = {};
  for (const [k, v] of Object.entries(headers)) {
    const key = k.toLowerCase();
    const val = Array.isArray(v) ? v.join('; ') : String(v ?? '');
    if (key === 'authorization') {
      const m = /^Bearer\s+(.*)$/i.exec(val);
      out[k] = m
        ? `Bearer ${m[1].slice(0, 12)}…${m[1].slice(-8)} (${m[1].length} chars)`
        : '[redacted]';
    } else if (key === 'cookie' || key === 'set-cookie') {
      out[k] = val
        .split(/;\s*/)
        .map((c) => {
          const i = c.indexOf('=');
          if (i < 0) return c;
          const name = c.slice(0, i);
          const value = c.slice(i + 1);
          return value.length > 16 ? `${name}=${value.slice(0, 8)}…(${value.length})` : c;
        })
        .join('; ');
    } else {
      out[k] = val;
    }
  }
  return out;
}

function clip(buf) {
  if (!buf?.length) return { body: '', bytes: 0, truncated: false };
  const bytes = buf.length;
  const slice = buf.subarray(0, MAX_BODY).toString('utf8');
  return { body: slice, bytes, truncated: bytes > MAX_BODY };
}

function broadcast(event, payload) {
  const frame = `event: ${event}\ndata: ${JSON.stringify(payload)}\n\n`;
  for (const res of clients) {
    try {
      res.write(frame);
    } catch {
      clients.delete(res);
    }
  }
}

function record(call) {
  calls.push(call);
  if (calls.length > MAX_CALLS) calls.splice(0, calls.length - MAX_CALLS);
  broadcast('call', call);
}

/** Aggregate per normalized route+method. */
function buildStats() {
  const byKey = new Map();
  for (const c of calls) {
    const key = `${c.method} ${c.route}`;
    let s = byKey.get(key);
    if (!s) {
      s = { key, method: c.method, route: c.route, count: 0, ok: 0, err: 0, rl: 0, times: [] };
      byKey.set(key, s);
    }
    s.count += 1;
    if (c.status >= 200 && c.status < 400) s.ok += 1;
    else s.err += 1;
    if (c.status === 429) s.rl += 1;
    s.times.push(c.durationMs);
  }
  const pct = (arr, p) => {
    if (!arr.length) return 0;
    const a = [...arr].sort((x, y) => x - y);
    return a[Math.min(a.length - 1, Math.floor((p / 100) * a.length))];
  };
  return [...byKey.values()]
    .map((s) => ({
      key: s.key,
      method: s.method,
      route: s.route,
      count: s.count,
      ok: s.ok,
      err: s.err,
      rl: s.rl,
      avg: s.times.reduce((a, b) => a + b, 0) / s.times.length,
      p95: pct(s.times, 95),
      max: Math.max(...s.times),
      // Summed time across every call to this route — what avg alone hides. A cheap
      // route called 200 times can cost more than an expensive one called twice.
      total: s.times.reduce((a, b) => a + b, 0),
    }))
    .sort((a, b) => b.count - a.count);
}

/* ─────────────────────────── proxy ─────────────────────────── */

/**
 * Dedicated keep-alive agent. The default global agent proved unable to sustain ~20
 * concurrent journeys: sockets were reused after the upstream had closed them and the
 * proxy surfaced `socket hang up`, which looked exactly like an API failure and made
 * the monitor lie about the thing it exists to measure.
 */
const agent = new http.Agent({
  // keepAlive is deliberately OFF. Reused sockets are the classic source of
  // intermittent "socket hang up" in a Node proxy: the upstream closes an idle
  // connection, the agent hands that same socket to the next request, and it dies
  // mid-flight. That flakiness is fatal here, because the monitor's whole job is to
  // report on someone else's reliability — it must not invent failures of its own.
  // A fresh connection per request costs a little throughput and buys determinism.
  keepAlive: false,
  maxSockets: Number(process.env.MAX_SOCKETS || 512),
  timeout: 120_000,
});

/**
 * Hop-by-hop headers are per-connection and must never be forwarded (RFC 9110 §7.6.1).
 * Passing the client's `connection` / `keep-alive` through was corrupting the upstream
 * connection lifecycle and is the other half of the hang-up bug above.
 */
const HOP_BY_HOP = new Set([
  'connection',
  'keep-alive',
  'proxy-authenticate',
  'proxy-authorization',
  'te',
  'trailer',
  'transfer-encoding',
  'upgrade',
]);

function forwardableHeaders(headers) {
  const out = {};
  for (const [k, v] of Object.entries(headers)) {
    if (!HOP_BY_HOP.has(k.toLowerCase())) out[k] = v;
  }
  return out;
}

function handleProxy(req, res) {
  const started = process.hrtime.bigint();
  const startedAt = new Date().toISOString();
  const reqChunks = [];

  req.on('data', (c) => {
    if (reqChunks.reduce((n, b) => n + b.length, 0) < MAX_BODY * 2) reqChunks.push(c);
  });

  req.on('end', () => {
    const reqBuf = Buffer.concat(reqChunks);
    const target = new URL(req.url, upstream);

    const proxyReq = http.request(
      {
        protocol: upstream.protocol,
        hostname: upstream.hostname,
        port: upstream.port || (upstream.protocol === 'https:' ? 443 : 80),
        method: req.method,
        path: target.pathname + target.search,
        headers: { ...forwardableHeaders(req.headers), host: upstream.host },
        agent,
      },
      (proxyRes) => {
        const resChunks = [];
        proxyRes.on('data', (c) => {
          resChunks.push(c);
        });
        proxyRes.on('end', () => {
          const resBuf = Buffer.concat(resChunks);
          const durationMs = Number(process.hrtime.bigint() - started) / 1e6;

          res.writeHead(proxyRes.statusCode || 502, forwardableHeaders(proxyRes.headers));
          res.end(resBuf);

          record({
            id: ++seq,
            startedAt,
            method: req.method,
            path: target.pathname,
            query: target.search || '',
            route: normalizePath(target.pathname),
            status: proxyRes.statusCode || 0,
            durationMs: Math.round(durationMs * 10) / 10,
            request: {
              headers: redactHeaders(req.headers),
              ...clip(reqBuf),
            },
            response: {
              headers: redactHeaders(proxyRes.headers),
              ...clip(resBuf),
            },
          });
        });
      },
    );

    proxyReq.on('error', (err) => {
      const durationMs = Number(process.hrtime.bigint() - started) / 1e6;
      if (!res.headersSent) res.writeHead(502, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ error: 'upstream_unreachable', detail: err.message }));
      record({
        id: ++seq,
        startedAt,
        method: req.method,
        path: target.pathname,
        query: target.search || '',
        route: normalizePath(target.pathname),
        status: 0,
        durationMs: Math.round(durationMs * 10) / 10,
        request: { headers: redactHeaders(req.headers), ...clip(reqBuf) },
        response: { headers: {}, body: `PROXY ERROR: ${err.message}`, bytes: 0, truncated: false },
      });
    });

    if (reqBuf.length) proxyReq.write(reqBuf);
    proxyReq.end();
  });
}

/* ─────────────────────────── server ─────────────────────────── */

const server = http.createServer((req, res) => {
  const url = new URL(req.url, `http://localhost:${PORT}`);

  if (url.pathname === '/__monitor/stream') {
    res.writeHead(200, {
      'content-type': 'text/event-stream',
      'cache-control': 'no-cache',
      connection: 'keep-alive',
    });
    res.write(`retry: 2000\n\n`);
    clients.add(res);
    req.on('close', () => clients.delete(res));
    return;
  }

  if (url.pathname === '/__monitor/calls') {
    const limit = Number(url.searchParams.get('limit') || 300);
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ calls: calls.slice(-limit), total: calls.length }));
    return;
  }

  if (url.pathname === '/__monitor/stats') {
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ stats: buildStats(), total: calls.length }));
    return;
  }

  if (url.pathname === '/__monitor/clear' && req.method === 'POST') {
    calls.length = 0;
    seq = 0;
    runMeta = null;
    broadcast('cleared', {});
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ ok: true }));
    return;
  }

  // The load script announces its own parameters here at setup time.
  if (url.pathname === '/__monitor/run') {
    if (req.method === 'POST') {
      const chunks = [];
      req.on('data', (c) => chunks.push(c));
      req.on('end', () => {
        try {
          runMeta = {
            ...JSON.parse(Buffer.concat(chunks).toString('utf8')),
            at: new Date().toISOString(),
          };
          broadcast('run', runMeta);
        } catch {
          /* a malformed announcement just leaves the dashboard on inference */
        }
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end(JSON.stringify({ ok: true }));
      });
      return;
    }
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ run: runMeta }));
    return;
  }

  if (url.pathname === '/' || url.pathname === '/index.html') {
    res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
    res.end(DASHBOARD_HTML);
    return;
  }

  // Answer the dashboard's own favicon here. Proxying it upstream would record a
  // 404 against the API and show the browser as a "client" in the stats — noise
  // that is entirely an artifact of viewing the dashboard.
  if (url.pathname === '/favicon.ico') {
    res.writeHead(204);
    res.end();
    return;
  }

  // Everything else is proxied upstream.
  handleProxy(req, res);
});

/**
 * Open a few upstream connections before serving traffic.
 *
 * Without this the agent's socket pool is empty, so the first burst of concurrent
 * clients each demand a fresh TCP connection at once and some fail — which showed up
 * as a whole load run failing on its first attempt and passing on every retry. Warming
 * the pool makes the first run behave like the ones after it.
 */
function warmUpstream(count = 8) {
  return Promise.all(
    Array.from(
      { length: count },
      () =>
        new Promise((resolve) => {
          const request = http.request(
            {
              protocol: upstream.protocol,
              hostname: upstream.hostname,
              port: upstream.port || 80,
              method: 'GET',
              path: '/readyz',
              agent,
            },
            (response) => {
              response.resume();
              response.on('end', resolve);
            },
          );
          request.on('error', () => resolve());
          request.end();
        }),
    ),
  );
}

server.listen(PORT, async () => {
  process.stdout.write(
    `\n  API monitor listening\n` +
      `    dashboard   http://localhost:${PORT}/\n` +
      `    proxying    http://localhost:${PORT}/api/*  ->  ${UPSTREAM}/api/*\n`,
  );
  await warmUpstream();
  process.stdout.write(`    upstream    connection pool warmed\n\n`);
});

