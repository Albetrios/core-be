const esc=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
const stCls=s=>s>=500||s===0?'bad':s>=400?(s===429?'warn':'bad'):'ok';
const pretty=b=>{if(!b)return '(empty)';try{return JSON.stringify(JSON.parse(b),null,2)}catch{return b}};
const hhmmss=iso=>{const d=new Date(iso);return d.toTimeString().slice(0,8)+'.'+String(d.getMilliseconds()).padStart(3,'0')};

function passes(c){
  const t=q.value.trim().toLowerCase();
  if(t&&!(c.path+c.query).toLowerCase().includes(t))return false;
  const f=fstatus.value;
  if(!f)return true;
  if(f==='429')return c.status===429;
  return String(c.status).startsWith(f);
}

function kpis(){
  const v=all;
  const ok=v.filter(c=>c.status>=200&&c.status<400).length;
  const rl=v.filter(c=>c.status===429).length;
  const t=v.map(c=>c.durationMs).sort((a,b)=>a-b);
  const p95=t.length?t[Math.min(t.length-1,Math.floor(.95*t.length))]:0;
  const avg=t.length?t.reduce((a,b)=>a+b,0)/t.length:0;
  const err=v.length-ok;
  document.getElementById('k-total').textContent=v.length;
  document.getElementById('k-ok').textContent=ok;
  const eEl=document.getElementById('k-err');
  eEl.textContent=err; eEl.className='v'+(err?' bad':'');
  const rEl=document.getElementById('k-rl');
  rEl.textContent=rl; rEl.className='v'+(rl?' warn':'');
  document.getElementById('k-avg').innerHTML=avg.toFixed(1)+'<small>ms</small>';
  document.getElementById('k-p95').innerHTML=p95.toFixed(1)+'<small>ms</small>';
  document.getElementById('k-routes').textContent=new Set(v.map(c=>c.method+' '+c.route)).size;

  // Two different "totals", and the gap between them is the interesting part:
  //   total time = wall clock from the first call starting to the last one finishing
  //   api time   = the sum of every call's duration
  // With concurrent clients api time EXCEEDS total time (work overlapped); with one
  // sequential client they converge, and the shortfall is client-side think time.
  const starts=v.map(c=>new Date(c.startedAt).getTime());
  const span=v.length?(Math.max(...v.map((c,i)=>starts[i]+c.durationMs))-Math.min(...starts)):0;
  const apiTime=v.reduce((a,c)=>a+c.durationMs,0);
  document.getElementById('k-span').innerHTML=fmtDur(span);
  document.getElementById('k-apitime').innerHTML=fmtDur(apiTime);

  // send-code fires exactly once per journey, so counting it counts journeys —
  // and calls/journey shows at a glance whether journeys are finishing all 16 steps.
  const journeys=v.filter(c=>c.route.endsWith('/auth/email/send-code')).length;
  const per=journeys?(v.length/journeys):0;
  document.getElementById('k-journeys').textContent=journeys;
  const pj=document.getElementById('k-perjourney');
  pj.textContent=journeys?per.toFixed(1):'0';
  pj.className='v'+(journeys&&per<12?' warn':'');
}

/** Same scaling as fmtDur but without markup — for table cells. */
function fmtPlain(ms){
  if(ms<1000)return ms.toFixed(0)+' ms';
  if(ms<60000)return (ms/1000).toFixed(2)+' s';
  return Math.floor(ms/60000)+'m '+Math.round((ms%60000)/1000)+'s';
}

/** ms -> "842ms" / "3.7s" / "1m 12s", so a long recording stays readable. */
function fmtDur(ms){
  if(ms<1000)return ms.toFixed(0)+'<small>ms</small>';
  if(ms<60000)return (ms/1000).toFixed(1)+'<small>s</small>';
  const m=Math.floor(ms/60000), s=Math.round((ms%60000)/1000);
  return m+'<small>m</small> '+s+'<small>s</small>';
}

/**
 * The monitor cannot know what was typed in another terminal, so it infers the client
 * from the User-Agent of recorded traffic and shows the command that produces it.
 */
function renderCommand(){
  const el=document.getElementById('cmdmain'), who=document.getElementById('cmdclient');

  // Exact parameters announced by the load script beat anything inferred from traffic.
  if(runMeta&&runMeta.command){
    const journeys=all.filter(c=>c.route.endsWith('/auth/email/send-code')).length;
    who.textContent=runMeta.mode?('mode: '+runMeta.mode):'announced';
    document.getElementById('k-pool').textContent=runMeta.poolMax??'\u2014';
    el.innerHTML='<span class="p">$</span> '+
      esc(runMeta.command).replace(/(BASE_URL=\\S+|VUS=\\d+|RAMP=\\S+|DURATION=\\S+|ITERATIONS=\\d+)/g,
        '<span class="e">$1</span>')+
      '\\n<span class="c"># '+journeys+' journey(s), '+all.length+' API call(s) recorded</span>';
    return;
  }

  if(!all.length){
    who.textContent='no traffic yet';
    el.innerHTML='<span class="c"># run a client through this proxy to record it</span>';
    return;
  }
  // Only API traffic identifies the client under test — and prefer a tool UA over a
  // browser one, so simply having the dashboard open does not relabel the run.
  const uas=all.filter(c=>c.path.startsWith('/api/'))
    .map(c=>c.request.headers['user-agent']||'').filter(Boolean);
  const tool=uas.filter(u=>/k6|curl|postman|insomnia|node|axios/i.test(u));
  const ua=(tool.length?tool[tool.length-1]:uas[uas.length-1])||'unknown';
  who.textContent=ua.slice(0,60);
  const api=all.filter(c=>c.path.startsWith('/api/'));
  // send-code fires exactly once per journey, so it counts journeys directly.
  const journeys=api.filter(c=>c.route.endsWith('/auth/email/send-code')).length;
  // Peak overlapping requests ~= the number of simulated users, recovered from the
  // recorded start/end times rather than guessed.
  const ev=[];
  for(const c of api){
    const s=new Date(c.startedAt).getTime();
    ev.push([s,1],[s+c.durationMs,-1]);
  }
  ev.sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
  let cur=0,peak=0;
  for(const [,d] of ev){cur+=d;if(cur>peak)peak=cur}
  const vus=Math.max(1,peak);
  // 16 calls per full journey — many more than that per journey means it looped.
  const looped=journeys>0&&api.length/journeys>20;
  const mode=looped?'DURATION=1m':'ITERATIONS=1';

  el.innerHTML='<span class="p">$</span> <span class="e">BASE_URL=http://localhost:${PORT}</span> '+
    '<span class="e">VUS='+vus+'</span> <span class="e">'+mode+'</span> \\\\\\n'+
    '    k6 run src/tests/load/k6/scenarios/fe-user-journey.js\\n'+
    (journeys
      ? '<span class="c"># '+journeys+' journey(s), '+api.length+' API call(s), peak concurrency '+vus+'</span>'
      : '<span class="c"># '+api.length+' API call(s) recorded &mdash; no journey traffic yet</span>')+
    (/k6/i.test(ua)?'':'\\n<span class="c"># note: current traffic is '+esc(ua.slice(0,40))+', not k6</span>');
}

